"""조력자 초상 96×96 — 기본 표정(웃음). W-023 본그림의 디자인 정본(D-107: H2 스트리트 러너, 서브컬처 화풍 강화).

- W-025(D-108): 둥근 실루엣(곡선을 래스터화해 계단이 고르게), 태블릿을 내려다보며 자연스럽게 웃는 표정.
  두 눈은 같은 높이·같은 크기(먼 쪽 눈만 1px 좁게), 닫힌 웃는 입(네모 입·이 표시 없음).
- 주인공 초상(portrait_hacker.py)과 같은 틀: 96×96, 얼굴 가운데 x=48, 어깨선 y≈76, 외곽선 1px(K).
- 공유 팔레트 + 인물 전용 추가 색(main_lobby.EXT: A·O·o·P·p·N). 안티앨리어싱 없음, 피부·머리에 디더 없음(볼 홍조 점 제외).
- 머리: 울프컷(정수리 볼륨·바보털·다발 4개·천사 링), 왼쪽 작은 묶음(주황 끈), 머리끝 주황. 귀에 통신 이어피스.
[시안] 사용자 확인 전. 대화창 초상은 범위 밖이며 이 그림은 디자인 정본으로만 쓴다.
"""
from artkit import EXPORT, canvas, draw_line, palette_check, pfill, pset, save, upscale
import main_lobby as ml
from main_lobby import O, S, curve, dots, eye_down, lines, put, shade, silhouette_outline, smile

N = 96


def portrait(eye=0):
    lay = canvas(N, N)
    # ---- 뒷머리(종 모양) + 왼쪽 작은 묶음 ----
    back = put(lay, S([(21, 50), (20, 36), (24, 24), (32, 14), (42, 10), (53, 10), (63, 14), (71, 24), (75, 36), (74, 50),
                       (77, 62, "c"), (71, 58), (67, 66, "c"), (62, 60), (56, 67, "c"), (50, 61), (45, 67, "c"), (39, 61),
                       (34, 66, "c"), (29, 59), (24, 66, "c"), (21, 58)]), "D", "d")
    shade(lay, back, [(10, 63), (90, 63), (90, 72), (10, 72)], "O")                       # 머리끝 주황
    lines(lay, [([(21, 62), (75, 62)], "d", 1)])
    for x in (26, 33, 40, 47, 54, 61, 68):
        lines(lay, [([(x, 44), (x + (x - 48) // 12, 62)], "d", 1)])
    pony = put(lay, S([(22, 40), (16, 44), (13, 51), (12, 60), (14, 67), (19, 71, "c"), (20, 62), (22, 52)]), "D", "d")
    shade(lay, pony, [(8, 62), (23, 62), (23, 74), (8, 74)], "O")
    put(lay, S([(14, 44), (22, 43), (23, 48), (14, 49)]), "O", "o")                        # 주황 끈
    lines(lay, [(O([(16, 51), (15, 56), (15, 60)], 0), "d", 1), ([(19, 51), (18, 60)], "A", 1)])
    # ---- 목·재킷·높은 칼라(둥근 어깨) ----
    neck = put(lay, S([(42, 62), (54, 62), (55, 70), (56, 78), (40, 78), (41, 70)]), "S", "s")
    shade(lay, neck, [(48, 62), (56, 62), (56, 78), (48, 78)], "s")
    shade(lay, neck, [(41, 62), (56, 62), (56, 70), (41, 70)], "s")
    jk = put(lay, S([(5, 95, "c"), (8, 88), (14, 82), (24, 78), (36, 75), (48, 74), (60, 75), (72, 78), (82, 82), (88, 88),
                     (91, 95, "c")]), "O", "o")
    shade(lay, jk, [(60, 75), (72, 78), (82, 82), (91, 95), (60, 95)], "o")
    pfill(lay, 8, 87, 9, 95, "A")
    lines(lay, [(O([(16, 86), (22, 81), (30, 78)], 0), "Y", 3), (O([(80, 86), (74, 81), (66, 78)], 0), "o", 3), ([(48, 84), (48, 95)], "K", 1)])
    lines(lay, [(O([(22, 88), (26, 92), (30, 94)], 0), "o", 1), (O([(70, 88), (66, 92), (64, 94)], 0), "o", 1)])
    col = put(lay, S([(36, 71), (41, 66), (48, 65), (55, 66), (60, 71), (62, 79), (48, 86), (34, 79)]), "O", "o")
    shade(lay, col, [(48, 66), (61, 70), (62, 80), (48, 86)], "o")
    lines(lay, [(O([(37, 72), (39, 69), (42, 68)], 0), "h", 1), ([(48, 70), (48, 85)], "K", 1)])
    pset(lay, 48, 72, "h"); pset(lay, 48, 73, "h")
    # ---- 얼굴(갸름한 턱 · 둥근 볼) ----
    face = put(lay, S([(29, 38), (33, 31), (41, 27), (55, 27), (63, 31), (67, 38), (68, 47), (66, 56), (61, 64), (54, 69),
                       (48, 70), (42, 69), (35, 64), (30, 56), (28, 47)]), "S", "s")
    shade(lay, face, [(60, 30), (69, 36), (69, 47), (66, 56), (61, 64), (54, 69), (58, 60), (62, 50)], "s")
    shade(lay, face, [(28, 27), (69, 27), (69, 36), (28, 36)], "s")                         # 앞머리 그림자
    shade(lay, face, [(38, 67), (58, 67), (54, 70), (42, 70)], "s")                         # 턱 밑
    # 이어피스(왼쪽 귀 자리)
    put(lay, S([(24, 46), (27, 45), (27, 53), (24, 54)], 6), "K", None)
    pfill(lay, 25, 47, 26, 52, "3"); pset(lay, 25, 48, "G"); pset(lay, 25, 49, "g")
    lines(lay, [(O([(25, 54), (24, 59), (22, 64)], 0), "K", 1)])
    # 눈썹(부드러운 곡선) · 눈(태블릿을 내려다봄, 같은 높이·같은 크기, 먼 쪽만 1px 좁게) · 코 · 입 · 볼 홍조
    curve(lay, [(31, 40), (35, 37), (41, 38)], "d", 2)
    curve(lay, [(55, 38), (61, 37), (65, 40)], "d", 2)
    eye_down(lay, 31, 41, 12, 10, -1, eye)
    eye_down(lay, 54, 41, 11, 10, +1, eye)
    dots(lay, [(49, 58)], "s"); dots(lay, [(48, 57), (47, 56)], "l")
    smile(lay, 48, 61, 5, 3)                                                                 # 닫힌 웃는 입
    dots(lay, [(34, 58), (35, 57), (36, 58), (35, 59), (60, 58), (61, 57), (62, 58), (61, 59)], "N")
    # ---- 앞머리·옆머리: 끝이 뾰족한 다발 4개, 다발 사이 어두운 틈, 천사 링, 바보털 ----
    front = put(lay, S([(28, 62, "c"), (26, 52), (26, 40), (29, 30), (37, 23), (47, 20), (58, 22), (66, 28), (70, 38),
                        (70, 52), (68, 63, "c"), (65, 52), (64, 44), (63, 39), (59, 37, "c"), (57, 31), (53, 38, "c"),
                        (49, 33), (45, 38, "c"), (41, 31), (37, 38, "c"), (34, 34), (32, 44), (31, 52)], 8), "D", "d")
    for (nx, ny, tx, ty) in ((57, 31, 59, 22), (49, 33, 49, 21), (41, 31, 39, 22), (34, 34, 32, 25)):
        curve(lay, [(nx, ny), ((nx + tx) // 2, (ny + ty) // 2 + 1), (tx, ty)], "d")
        curve(lay, [(nx - 2, ny - 1), (tx - 2, ty + 3)], "A")
    lines(lay, [([(29, 40), (30, 56)], "A", 1), ([(67, 40), (68, 54)], "d", 1)])
    shade(lay, front, [(66, 38), (71, 38), (71, 56), (68, 64)], "d")
    ring = [(28, 34), (31, 28), (37, 24), (44, 22), (52, 22), (60, 24), (66, 28), (69, 34)]
    curve(lay, ring, "A")
    curve(lay, [(p[0], p[1] - 1) for p in ring[2:-2]], "h")
    curve(lay, [(47, 20), (46, 14), (49, 10), (54, 9)], "D")
    lines(lay, [([(48, 15), (49, 12)], "A", 1)])
    dots(lay, [(54, 9)], "d")
    for tx, ty in ((60, 37), (54, 38), (46, 38), (38, 38)):
        dots(lay, [(tx, ty), (tx, ty - 1), (tx - 1, ty - 1)], "O")
    pfill(lay, 28, 59, 30, 63, "O"); pfill(lay, 66, 59, 68, 63, "O")
    silhouette_outline(lay, "K")
    return lay


def build():
    with ml.ext_palette():
        im = portrait()
        bad = ml.bad_colors(im)
        assert not bad, bad
        made = [save(im, "portraits/helper_joy.png", {"status": "시안", "style": "pixel", "size": 96, "expression": "joy",
                                                      "note": "W-023 조력자 H2 디자인 정본, W-025 둥근 형태·내려다보는 미소(대화창은 범위 밖)"})]
        pv = EXPORT / "preview" / "main_lobby_helper_portrait_x4.png"
        upscale(im, 4).save(pv)
        made.append(pv)
    return made
