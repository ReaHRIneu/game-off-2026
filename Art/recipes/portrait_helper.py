"""조력자 초상 96×96 — 기본 표정(웃음). W-023 본그림의 디자인 정본(D-107: H2 스트리트 러너, 서브컬처 화풍 강화).

- 주인공 초상(portrait_hacker.py)과 같은 틀: 96×96, 얼굴 가운데 x=48, 어깨선 y≈76, 외곽선 1px(K).
- 공유 팔레트 + 인물 전용 추가 색(main_lobby.EXT: A·O·o·P·p·N). 안티앨리어싱 없음, 피부·머리에 디더 없음(볼 홍조 점 제외).
- 눈: 폭 10·높이 11(얼굴 43px의 약 1/4), 굵은 윗속눈썹(눈꼬리 1px 바깥), 홍채 위 어둡게→아래 밝게, 하이라이트 2점.
- 머리: 울프컷(정수리 볼륨·바보털·다발 4개·천사 링), 왼쪽 작은 묶음(주황 끈), 머리끝 주황. 귀에 통신 이어피스.
[시안] 사용자 확인 전. 대화창 초상은 범위 밖이며 이 그림은 디자인 정본으로만 쓴다.
"""
from artkit import EXPORT, canvas, draw_line, palette_check, pfill, pset, save, upscale
import main_lobby as ml
from main_lobby import dots, eye_shape, lines, put, shade, silhouette_outline

N = 96


def portrait(eye=0):
    lay = canvas(N, N)
    # ---- 뒷머리(종 모양) + 왼쪽 작은 묶음 ----
    back = put(lay, [(21, 50), (20, 36), (24, 24), (32, 14), (42, 10), (53, 10), (63, 14), (71, 24), (75, 36), (74, 50),
                     (76, 60), (72, 65), (68, 61), (64, 66), (58, 62), (52, 67), (46, 63), (40, 67), (34, 62), (30, 66),
                     (26, 61), (22, 65), (20, 60)], "D", "d")
    shade(lay, back, [(10, 63), (90, 63), (90, 72), (10, 72)], "O")                       # 머리끝 주황
    lines(lay, [([(20, 62), (76, 62)], "d", 1)])
    for x in (26, 33, 40, 47, 54, 61, 68):
        lines(lay, [([(x, 44), (x + (x - 48) // 12, 62)], "d", 1)])
    pony = put(lay, [(21, 40), (16, 44), (13, 51), (12, 60), (15, 67), (19, 70), (20, 62), (21, 52)], "D", "d")
    shade(lay, pony, [(8, 62), (22, 62), (22, 74), (8, 74)], "O")
    put(lay, [(14, 44), (22, 43), (22, 48), (14, 49)], "O", "o")                          # 주황 끈
    lines(lay, [([(16, 51), (15, 60)], "d", 1), ([(19, 51), (18, 60)], "A", 1)])
    # ---- 목·재킷·높은 칼라 ----
    neck = put(lay, [(42, 62), (54, 62), (55, 78), (41, 78)], "S", "s")
    shade(lay, neck, [(48, 62), (55, 62), (55, 78), (48, 78)], "s")
    shade(lay, neck, [(41, 62), (55, 62), (55, 70), (41, 70)], "s")
    jk = put(lay, [(6, 95), (12, 84), (26, 77), (36, 75), (60, 75), (70, 77), (84, 84), (90, 95)], "O", "o")
    shade(lay, jk, [(60, 75), (70, 77), (84, 84), (90, 95), (60, 95)], "o")
    pfill(lay, 8, 85, 9, 95, "A")
    lines(lay, [([(16, 86), (30, 78)], "Y", 3), ([(80, 86), (66, 78)], "o", 3), ([(48, 84), (48, 95)], "K", 1)])
    lines(lay, [([(22, 88), (30, 94)], "o", 1), ([(70, 88), (64, 94)], "o", 1)])
    col = put(lay, [(36, 70), (42, 66), (54, 66), (60, 70), (62, 80), (48, 86), (34, 80)], "O", "o")
    shade(lay, col, [(48, 66), (60, 70), (62, 80), (48, 86)], "o")
    lines(lay, [([(37, 71), (42, 68)], "h", 1), ([(48, 70), (48, 85)], "K", 1)])
    pset(lay, 48, 72, "h"); pset(lay, 48, 73, "h")
    # ---- 얼굴(갸름한 턱 · 둥근 볼) ----
    face_pts = [(29, 36), (33, 30), (41, 27), (55, 27), (63, 30), (67, 36), (68, 46), (66, 56), (61, 64), (54, 69),
                (48, 70), (42, 69), (35, 64), (30, 56), (28, 46)]
    face = put(lay, face_pts, "S", "s")
    shade(lay, face, [(60, 30), (68, 36), (68, 46), (66, 56), (61, 64), (54, 69), (58, 60), (62, 50)], "s")
    shade(lay, face, [(28, 27), (68, 27), (68, 35), (28, 35)], "s")                         # 앞머리 그림자
    shade(lay, face, [(38, 67), (58, 67), (54, 70), (42, 70)], "s")                         # 턱 밑
    # 이어피스(왼쪽 귀 자리)
    pfill(lay, 24, 45, 27, 53, "K"); pfill(lay, 25, 46, 26, 52, "3"); pset(lay, 25, 47, "G"); pset(lay, 25, 48, "g")
    lines(lay, [([(25, 54), (22, 64)], "K", 1)])
    # 눈썹 · 눈(폭 10·높이 11) · 코 · 입 · 볼 홍조
    lines(lay, [([(32, 38), (36, 36), (42, 37)], "d", 2), ([(54, 37), (60, 36), (64, 38)], "d", 2)])
    eye_shape(lay, 33, 41, 10, -1, eye, h=11)
    eye_shape(lay, 53, 41, 10, +1, eye, h=11)
    dots(lay, [(49, 59)], "s"); dots(lay, [(48, 58), (47, 57)], "l")
    lines(lay, [([(42, 62), (43, 63), (44, 64), (52, 64), (53, 63), (54, 62)], "K", 1)])      # 웃는 선
    pfill(lay, 45, 65, 51, 65, "K"); pfill(lay, 46, 66, 50, 66, "N"); pset(lay, 45, 66, "K"); pset(lay, 51, 66, "K")
    pfill(lay, 47, 67, 49, 67, "K")                                                          # 작게 열린 입
    dots(lay, [(34, 58), (35, 57), (36, 58), (35, 59), (60, 58), (61, 57), (62, 58), (61, 59)], "N")
    # ---- 앞머리·옆머리: 끝이 뾰족한 다발 4개, 다발 사이 어두운 틈, 천사 링, 바보털 ----
    front = put(lay, [(27, 54), (26, 38), (30, 28), (38, 22), (48, 20), (58, 22), (66, 28), (70, 38), (69, 54),
                      (67, 64), (64, 66), (64, 52), (63, 44), (62, 38), (59, 36), (56, 31), (53, 38), (49, 33),
                      (45, 37), (41, 31), (37, 37), (34, 33), (32, 44), (31, 52), (31, 66), (28, 63)], "D", "d")
    for (nx, ny, tx, ty) in ((56, 31, 58, 22), (49, 33, 49, 21), (41, 31, 39, 22), (34, 33, 32, 25)):
        lines(lay, [([(nx, ny), ((nx + tx) // 2, (ny + ty) // 2 + 1), (tx, ty)], "d", 1)])
        lines(lay, [([(nx - 2, ny - 1), (tx - 2, ty + 3)], "A", 1)])
    lines(lay, [([(29, 40), (30, 56)], "A", 1), ([(66, 40), (67, 54)], "d", 1)])
    shade(lay, front, [(66, 38), (71, 38), (70, 56), (67, 66)], "d")
    ring = [(28, 33), (31, 28), (37, 24), (44, 22), (52, 22), (60, 24), (66, 28), (69, 33)]
    lines(lay, [(ring, "A", 1), ([(p[0], p[1] - 1) for p in ring[2:-2]], "h", 1)])
    lines(lay, [([(47, 20), (46, 14), (49, 10), (54, 9)], "D", 1), ([(48, 15), (49, 12)], "A", 1)])
    dots(lay, [(54, 9)], "d")
    for tx, ty in ((59, 36), (53, 38), (45, 37), (37, 37)):
        dots(lay, [(tx, ty), (tx, ty - 1), (tx - 1, ty - 1)], "O")
    pfill(lay, 28, 61, 30, 65, "O"); pfill(lay, 65, 61, 67, 65, "O")
    silhouette_outline(lay, "K")
    return lay


def build():
    with ml.ext_palette():
        im = portrait()
        bad = ml.bad_colors(im)
        assert not bad, bad
        made = [save(im, "portraits/helper_joy.png", {"status": "시안", "style": "pixel", "size": 96, "expression": "joy",
                                                      "note": "W-023 조력자 H2 디자인 정본(대화창은 범위 밖)"})]
        pv = EXPORT / "preview" / "main_lobby_helper_portrait_x4.png"
        upscale(im, 4).save(pv)
        made.append(pv)
    return made
