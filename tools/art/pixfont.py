W, H, SP = 5, 7, 1


def text_width(s: str) -> int:
    return len(s) * (W + SP) - SP if s else 0


def draw_text(im: Image.Image, x: int, y: int, s: str, ch: str) -> int:
    """대문자로 바꿔 그린다. 반환값: 그린 폭."""
    px = im.load()
    for i, c in enumerate(s.upper()):
        rows = G.get(c, G["?"]).split("|")
        for gy, row in enumerate(rows):
            for gx, v in enumerate(row):
                if v == "#":
                    X, Y = x + i * (W + SP) + gx, y + gy
                    if 0 <= X < im.width and 0 <= Y < im.height:
                        px[X, Y] = PIX[ch]
    return text_width(s)


def atlas(ch: str = "W") -> tuple[Image.Image, dict]:
    """Unity 비트맵 글꼴용 아틀라스(16열) + 글자 좌표."""
    keys = list(G)
    cols = 16
    rows = (len(keys) + cols - 1) // cols
    im = Image.new("RGBA", (cols * (W + 1), rows * (H + 1)), (0, 0, 0, 0))
    meta = {}
    for i, k in enumerate(keys):
        x, y = (i % cols) * (W + 1), (i // cols) * (H + 1)
        draw_text(im, x, y, k, ch)
        meta[k] = [x, y, W, H]
    return im, meta
